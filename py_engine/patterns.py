SMALL_ID_DIGITS = 2


def derive_small_id(big_id: str) -> str:
    return big_id[-SMALL_ID_DIGITS:] if len(big_id) >= SMALL_ID_DIGITS else big_id


def get_pattern(name: str) -> FieldPattern | None:
    for p in PATTERNS:
        if p.name == name:
            return p
    return None
